import { chromium } from 'playwright-core';
import { openPlan } from './lib/open-plan.mjs';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1180, height: 820 }, deviceScaleFactor: 2 });
await page.goto('http://localhost:5180/?store=memory'); await page.waitForTimeout(3500);
await page.evaluate(() => localStorage.setItem('plan-builder.shape.outline', 'rect'));
await page.reload(); await page.waitForTimeout(3500);
await openPlan(page, '../samples/riesberg-plot-plan.pdf');
await page.$eval('#snap', b => b.click());
const toScreen = ([x, y]) => page.evaluate(([x, y]) => { const r = document.getElementById('page').getBoundingClientRect(); return [r.left + x * r.width / 612, r.top + y * r.height / 1008]; }, [x, y]);
const drag = async (p, q) => { const a = await toScreen(p), b = await toScreen(q); await page.mouse.move(...a); await page.mouse.down(); await page.mouse.move(...b, { steps: 6 }); await page.mouse.up(); await page.waitForTimeout(200); };
const tap = async p => { await page.mouse.click(...await toScreen(p)); await page.waitForTimeout(250); };
await page.click('[data-start=boundary]'); await drag([250, 150], [550, 650]); await page.keyboard.press('Escape');
await tap([250, 560]); await page.fill('#edge-len', '100'); await page.click('.popover button[type=submit]'); await page.keyboard.press('Escape');
await page.click('[data-act=add-surface]'); await page.click('#surfaces .layer-form [data-material=premium-sod]');
const sh = await page.$$eval('#shape button', b => b.map(x => x.textContent.trim() + ':' + x.getAttribute('aria-pressed')));
console.log('shape buttons', sh);
await page.click('#shape button:has-text("Freehand")');
for (const p of [[300, 200], [500, 220], [520, 400], [420, 450], [310, 380]]) await tap(p);
await tap([300, 200]); await page.waitForTimeout(300);
console.log('card?', !!(await page.$('#surfaces [data-card]')), 'round-all?', !!(await page.$('#surfaces .round-all')), 'drawing:', (await page.textContent('#surfaces')).replace(/\s+/g,' ').slice(0,150));
await page.screenshot({ path: process.argv[2] + '/round1.png' });
await browser.close();
